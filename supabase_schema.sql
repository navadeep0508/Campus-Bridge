create table if not exists public.timetable_entries (
    id bigint generated by default as identity primary key,
    faculty_id bigint not null references public.users(id) on delete cascade,
    subject text not null check (char_length(subject) between 1 and 120),
    semester integer not null check (semester between 1 and 8),
    section text not null check (char_length(section) between 1 and 40),
    day_of_week text not null check (day_of_week in ('Monday','Tuesday','Wednesday','Thursday','Friday','Saturday')),
    starts_at text not null check (starts_at ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    ends_at text not null check (ends_at ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    room text check (char_length(room) <= 80),
    created_at timestamptz not null default now(),
    constraint timetable_entries_valid_time check (starts_at < ends_at)
);

create index if not exists timetable_entries_group_idx
    on public.timetable_entries (semester, section, day_of_week, starts_at);
create index if not exists timetable_entries_faculty_idx
    on public.timetable_entries (faculty_id, day_of_week, starts_at);

create table if not exists public.attendance_records (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public.users(id) on delete cascade,
    section text not null,
    faculty_id bigint not null references public.users(id) on delete cascade,
    attendance_date date not null,
    status text not null check (status in ('present', 'absent')),
    constraint attendance_records_once_per_day unique (student_id, section, attendance_date)
);

create index if not exists attendance_records_student_section_idx
    on public.attendance_records (student_id, section);

create table if not exists public.problem_solutions (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    problem_id integer not null,
    solved_at timestamptz not null default now(),
    constraint problem_solutions_once unique (user_id, problem_id)
);

create table if not exists public.assessment_solutions (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    assessment_id bigint not null references public.coding_assessments(id) on delete cascade,
    solved_at timestamptz not null default now(),
    constraint assessment_solutions_once unique (user_id, assessment_id)
);

create or replace function public.award_problem_points(
    p_user_id bigint,
    p_problem_id integer,
    p_points integer
) returns boolean
language plpgsql
as $$
declare
    inserted_rows integer;
begin
    insert into public.problem_solutions (user_id, problem_id)
    values (p_user_id, p_problem_id)
    on conflict (user_id, problem_id) do nothing;
    get diagnostics inserted_rows = row_count;
    if inserted_rows = 1 then
        update public.users
        set points = coalesce(points, 0) + greatest(coalesce(p_points, 0), 0)
        where id = p_user_id;
    end if;
    return inserted_rows = 1;
end;
$$;

